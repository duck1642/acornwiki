const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const path = require('node:path');
const net = require('node:net');
(async () => {
  const server = net.createServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const port = server.address().port;
  await new Promise(resolve => server.close(resolve));
  const baseUrl = `http://127.0.0.1:${port}`;
  const vite = spawn(process.execPath, [path.resolve(__dirname, '../node_modules/vite/bin/vite.js'), '--host', '127.0.0.1', '--port', String(port), '--strictPort'], {cwd:path.resolve(__dirname, '..'), stdio:'ignore'});
  let browser;
  try {
    for (let attempt = 0; ; attempt++) {
      try { if ((await fetch(baseUrl)).ok) break; } catch {}
      if (attempt >= 100 || vite.exitCode !== null) throw Error('Vite did not start');
      await new Promise(resolve => setTimeout(resolve, 100));
    }
    browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
    const page = await browser.newPage();
    await page.addInitScript(() => {
      let content = '# Initial', version = '1', rev = 0, hold = false, release;
      const state = new EventTarget();
      const signal = () => state.dispatchEvent(new CustomEvent('change',{detail:{key:'note_revision'}}));
      const items = [{name:'note.md',is_directory:false,modified_time:null},{name:'other.md',is_directory:false,modified_time:null},{name:'run.exe',is_directory:false,modified_time:null}];
      const nested = [];
      const snap = () => ({workspace_id:'w',revision:++rev,watcher_error:null,directories:[{workspace_id:'w',path:'',items,loading:false,stale:false,error:null},{workspace_id:'w',path:'Created',items:nested,loading:false,stale:false,error:null}]});
      const create = (directory, name, isDirectory) => { const list=directory ? nested : items; if(list.some(item=>item.name===name)) throw Error('already exists'); list.push({name,is_directory:isDirectory,modified_time:null}); };
      window.external = (text, notify=true) => { content=text; version=String(Number(version)+1); if (notify) signal(); };
      window.restore = () => { content='# Initial'; version='1'; signal(); };
      window.disk = () => content;
      window.holdSave = () => { hold = true };
      window.releaseSave = () => { hold = false; release() };
      window.requestClose = () => state.dispatchEvent(new CustomEvent('change',{detail:{key:'close_request'}}));
      window.didClose = false;
      window.pywebview = {state,api:{create_note:async(id,dir,name)=>{const file=name.endsWith('.md')?name:`${name}.md`;create(dir,file,false);return file},create_directory:async(id,dir,name)=>{create(dir,name,true);return name},set_directory_visible:async()=>snap(),media_url:async()=> 'http://127.0.0.1:12345/image',resolve_note_link:async(id,note,href)=>{const [path,fragment='']=href.split('#');return {path,fragment}},open_workspace_file:async(id,path)=>{window.openedFile = {id,path};return true},open_external_link:async()=>{},finish_close:async()=>{window.didClose=true},get_settings:async()=>({workspaces:['test'],blocked_extensions:[],editor:{autosave:false,auto_reload:true,reload_notice:true}}),set_editor_preference:async()=>{},set_active_note:async()=>{},get_workspace_settings:async()=>({}),open_workspace:async()=>snap(),get_tree:async()=>snap(),refresh_tree:async()=>snap(),read_note:async(id,path)=>{if(content===null) throw Error('missing'); return {path,content,version}},save_note:async(id,path,text,expected)=>{if(hold) await new Promise(r=>release=r); if(content===null || expected!==version) throw Error('conflict'); content=text;version=String(Number(version)+1);return {path,content,version}}}};
    });
    await page.goto(baseUrl);
    await page.getByRole('button',{name:'test',exact:true}).click();
    page.once('dialog', dialog => dialog.accept('Created'));
    await page.getByRole('button',{name:'New folder',exact:true}).click();
    await page.getByRole('button',{name:'Created',exact:true}).click();
    await page.getByLabel('Destination').selectOption('Created');
    page.once('dialog', dialog => dialog.accept('Draft'));
    await page.getByRole('button',{name:'New note',exact:true}).click();
    await page.getByRole('button',{name:'Draft.md',exact:true}).waitFor();
    page.once('dialog', dialog => dialog.accept('Draft'));
    await page.getByRole('button',{name:'New note',exact:true}).click();
    await page.getByText('Could not create the item. Check its name, location, and whether it already exists.').waitFor();
    await page.getByRole('button',{name:'note.md',exact:true}).click();
    await page.locator('.cm-content').waitFor();
    await page.locator('.cm-content').click();
    await page.keyboard.press('End'); await page.keyboard.type(' edited');
    await page.getByRole('button',{name:'Read',exact:true}).click();
    assert.equal(await page.locator('.note-read h1').innerText(), 'Initial edited');
    await page.getByRole('button',{name:'Source',exact:true}).click();
    await page.locator('.cm-content').focus();
    await page.keyboard.press('Control+z');
    assert.equal(await page.locator('.cm-content').innerText(), '# Initial');
    await page.keyboard.press('Control+y');
    await page.keyboard.press('Control+s');
    await page.getByText('Saved.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(() => window.disk()), '# Initial edited');
    await page.evaluate(() => window.external('# Remote'));
    await page.getByText('File changed externally and was reloaded.').waitFor();
    await page.locator('.cm-content').click(); await page.keyboard.press('End'); await page.keyboard.type(' local');
    await page.evaluate(() => window.external('# Other'));
    await page.getByText('File changed externally. Your editor content was kept.').waitFor();
    assert.equal(await page.locator('.cm-content').innerText(), '# Remote local');
    await page.getByRole('button',{name:'other.md',exact:true}).click();
    await page.getByText('You have unsaved changes.').waitFor();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await page.locator('.cm-content').innerText(), '# Remote local');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button',{name:'Overwrite with editor version'}).click();
    await page.getByText('Saved.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(() => window.disk()), '# Remote local');
    await page.getByLabel('Autosave').check();
    await page.locator('.cm-content').focus(); await page.keyboard.press('End'); await page.keyboard.type(' autosave');
    await page.waitForFunction(() => window.disk() === '# Remote local autosave');
    await page.getByLabel('Autosave').uncheck();
    await page.evaluate(() => window.holdSave());
    await page.locator('.cm-content').focus();
    await page.keyboard.type(' first');
    await page.keyboard.press('Control+s');
    await page.keyboard.type(' later');
    await page.evaluate(() => window.releaseSave());
    await page.getByText('Unsaved',{exact:true}).waitFor();
    await page.waitForFunction(() => window.disk() === '# Remote local autosave first');
    assert.equal(await page.locator('.cm-content').innerText(), '# Remote local autosave first later');
    assert.equal(await page.getByText('Saved.', {exact:true}).count(), 0);
    await page.evaluate(() => window.requestClose());
    await page.getByText('You have unsaved changes.').waitFor();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await page.evaluate(() => window.didClose), false);
    await page.evaluate(() => window.requestClose());
    await page.getByRole('button',{name:'Discard',exact:true}).click();
    await page.waitForFunction(() => window.didClose);
    await page.reload();
    await page.getByRole('button',{name:'test',exact:true}).click();
    await page.getByRole('button',{name:'note.md',exact:true}).click();
    await page.locator('.cm-content').waitFor();
    await page.getByLabel('Auto-reload unchanged notes').uncheck();
    await page.evaluate(() => window.external('# Notify'));
    await page.getByText('File changed externally. Your editor content was kept.').waitFor();
    assert.equal(await page.locator('.cm-content').innerText(), '# Initial');
    await page.getByRole('button',{name:'Load disk version'}).click();
    assert.equal(await page.locator('.cm-content').innerText(), '# Notify');
    await page.locator('.cm-content').focus();
    await page.keyboard.press('End'); await page.keyboard.type(' local');
    await page.evaluate(() => window.external('# Missed event', false));
    await page.keyboard.press('Control+s');
    await page.getByText('File changed externally. Your editor content was kept.').waitFor();
    assert.equal(await page.evaluate(() => window.disk()), '# Missed event');
    assert.equal(await page.locator('.cm-content').innerText(), '# Notify local');
    await page.evaluate(() => window.external(null));
    await page.getByText('File cannot be read; it may have been moved or deleted. Your editor content was kept.').waitFor();
    assert.equal(await page.locator('.cm-content').innerText(), '# Notify local');
    await page.reload();
    await page.getByRole('button',{name:'test',exact:true}).click();
    await page.getByRole('button',{name:'note.md',exact:true}).click();
    await page.locator('.cm-content').waitFor();
    await page.getByLabel('Autosave').check();
    await page.locator('.cm-content').focus();
    await page.keyboard.press('End'); await page.keyboard.type(' local');
    await page.evaluate(() => window.external('# Conflict'));
    await page.getByText('File changed externally. Your editor content was kept.').waitFor();
    await page.evaluate(() => window.restore());
    await page.waitForFunction(() => window.disk() === '# Initial local');
    await page.evaluate(() => window.external('![Picture](images/photo.png)\n\n[Page](guide.pdf#page=3)\n\n[Guide](guide.pdf)\n\n[Other](other.md)'));
    await page.getByText('File changed externally and was reloaded.').waitFor();
    await page.getByRole('button',{name:'Read',exact:true}).click();
    const imageSrc = await page.locator('.note-read img').getAttribute('src');
    const imageUrl = new URL(imageSrc);
    assert.equal(imageUrl.searchParams.get('note'), 'note.md');
    assert.equal(imageUrl.searchParams.get('src'), 'images/photo.png');
    await page.getByRole('link',{name:'Page',exact:true}).click();
    await page.getByText('Opening a specific section of this file is not supported.').waitFor();
    assert.equal(await page.evaluate(() => window.openedFile), undefined);
    await page.getByRole('link',{name:'Guide'}).click();
    await page.waitForFunction(() => window.openedFile?.path === 'guide.pdf');
    assert.deepEqual(await page.evaluate(() => window.openedFile), {id:'w',path:'guide.pdf'});
    await page.evaluate(() => {
      window.pywebview.api.open_workspace_file = async () => false;
      window.pywebview.api.reveal_workspace_file = async (id, path) => { window.revealedFile = {id, path} };
    });
    page.once('dialog', dialog => dialog.dismiss());
    await page.getByRole('button',{name:'run.exe',exact:true}).click();
    assert.equal(await page.evaluate(() => window.revealedFile), undefined);
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button',{name:'run.exe',exact:true}).click();
    await page.waitForFunction(() => window.revealedFile?.path === 'run.exe');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('link',{name:'Guide'}).click();
    await page.waitForFunction(() => window.revealedFile?.path === 'guide.pdf');
    await page.getByRole('link',{name:'Other'}).click();
    await page.getByText('other.md',{exact:true}).first().waitFor();
    await page.evaluate(() => {
      const api = window.pywebview.api;
      api.list_plan_notes = async () => ['note.md'];
      api.read_plan_notes = async () => ({notes:[{path:'note.md',content:'[link](other.md)',version:'v1'}],next_index:1});
      api.plan_link_targets_batch = async () => [['renamed.md']];
      api.commit_move = async (id, source, destination, snapshots, rewrites) => {
        window.moveResult = {id, source, destination, snapshots, rewrites};
        return {destination, updated:['note.md'], failures:[]};
      };
    });
    await page.getByRole('button',{name:'Source',exact:true}).click();
    await page.locator('.cm-content').click();
    await page.keyboard.press('End'); await page.keyboard.type(' unsaved');
    page.once('dialog', dialog => dialog.accept('renamed.md'));
    await page.getByRole('button',{name:'Move or rename other.md'}).click();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await page.evaluate(() => window.moveResult), undefined);
    assert.ok((await page.locator('.cm-content').innerText()).includes('unsaved'));
    page.once('dialog', dialog => dialog.accept('renamed.md'));
    await page.getByRole('button',{name:'Move or rename other.md'}).click();
    await page.getByRole('button',{name:'Discard',exact:true}).click();
    await page.getByText('Moved. Updated links in 1 notes.').waitFor();
    const moved = await page.evaluate(() => window.moveResult);
    assert.equal(moved.source, 'other.md');
    assert.equal(moved.destination, 'renamed.md');
    assert.equal(moved.rewrites[0].content, '[link](renamed.md)');
    console.log('headless editor checks passed');
  } finally { if (browser) await browser.close(); vite.kill() }
})().catch(error => { console.error(error); process.exit(1) });
